def main():
    number1 = 12
    number2 = 4

    # If one operand is a float, the resulting value will be a float type
    # Else, the resulting value will be an int type.
    addition = number1 + number2
    subtraction = number1 - number2
    mult = number1 * number2
    power = number1 ** number2
    floor_div = number1 // number2
    print(floor_div)
    mod = number1 % number2
    print(mod)

    # It will always yield float
    division = number1 / number2




if __name__ == "__main__":
    main()